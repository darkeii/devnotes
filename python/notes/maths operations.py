x = 3.14
y = -2
z = 5

result = round(x)       #rounds off to the nearest int.
print(result)

result = abs(y)     #absolute value is distance of number from 0
print(result)

result = pow(y, z)      #power func. = pow (base, exponent, mod)
print(result)

result = max(x,y,z)
print(result)

result = min(x,y,z)
print(result)